package compiler

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path"
	"strconv"
	"strings"
)

// generatedPropertySource emits strongly typed JSON methods for DTOs containing
// property decorators. No DTO field reflection or dynamic decorator registry
// is required on the HTTP request/response path.
func generatedPropertySource(file *File, structTypes map[string]bool) ([]byte, error) {
	if len(file.DTOs) == 0 {
		return nil, nil
	}
	imports := map[string]string{}
	astFile, err := parser.ParseFile(token.NewFileSet(), file.Path, file.Source, parser.ImportsOnly)
	if err != nil {
		return nil, err
	}
	for _, spec := range astFile.Imports {
		importPath, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, err
		}
		alias := path.Base(importPath)
		if spec.Name != nil {
			alias = spec.Name.Name
		}
		imports[alias] = importPath
	}
	required := map[string]string{}
	needsTransform := false
	needsValidate := anyDTOValidators(file)
	needsRegexp := hasRegexValidators(file)
	for _, dto := range file.DTOs {
		for _, field := range dto.Fields {
			parsedType, parseErr := parser.ParseExpr(field.Type)
			if parseErr != nil {
				return nil, Diagnostic{file.Path, 1, "invalid DTO field type"}
			}
			ast.Inspect(parsedType, func(node ast.Node) bool {
				selector, ok := node.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				id, ok := selector.X.(*ast.Ident)
				if !ok {
					return true
				}
				if uri, found := imports[id.Name]; found {
					required[id.Name] = uri
				}
				return true
			})
			for _, ann := range field.Annotations {
				if ann.Name == "Validate" {
					fn, _ := transformerSpec(ann.Argument)
					if alias := transformerQualifier(fn); alias != "" {
						uri, ok := imports[alias]
						if !ok { return nil, Diagnostic{file.Path, ann.Line, "unknown validator package " + alias} }
						required[alias] = uri
					}
				}
				if (ann.Name == "Transform" && field.excluded("input") && field.excluded("output")) ||
					(ann.Name == "TransformInput" && field.excluded("input")) ||
					(ann.Name == "TransformOutput" && field.excluded("output")) {
					continue
				}
				if ann.Name != "Transform" && ann.Name != "TransformInput" && ann.Name != "TransformOutput" {
					continue
				}
				fn, err := transformerSpec(ann.Argument)
				if err != nil {
					return nil, err
				}
				needsTransform = true
				if alias := transformerQualifier(fn); alias != "" {
					uri, ok := imports[alias]
					if !ok {
						return nil, Diagnostic{file.Path, ann.Line, fmt.Sprintf("unknown imported transformer package %s", alias)}
					}
					required[alias] = uri
				}
			}
		}
	}
	var out strings.Builder
	out.WriteString("// Code generated by NestGo compiler. DO NOT EDIT.\n")
	fmt.Fprintf(&out, "package %s\n\nimport (\n__nestgo_json \"encoding/json\"\n__nestgo_fmt \"fmt\"\n", file.Package)
	if needsTransform {
		out.WriteString("__nestgo_transform \"github.com/kevenmiano/nestgo/transform\"\n")
	}
	if needsValidate {
		out.WriteString("__nestgo_validation \"github.com/kevenmiano/nestgo/validation\"\n")
	}
	if needsRegexp {
		out.WriteString("__nestgo_regexp \"regexp\"\n")
	}
	aliases := make([]string, 0, len(required))
	for alias := range required {
		aliases = append(aliases, alias)
	}
	sortStrings(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(&out, "%s %s\n", alias, strconv.Quote(required[alias]))
	}
	out.WriteString(")\n")
	// Compile-time assertions are generated for every active transformer.
	// They guarantee that both function signatures and struct method sets
	// match the target DTO field. No type casting or runtime reflection.
	for _, dto := range file.DTOs {
		for _, field := range dto.Fields {
			for _, annotation := range field.Annotations {
				switch annotation.Name {
				case "Transform":
					if field.excluded("input") && field.excluded("output") {
						continue
					}
				case "TransformInput":
					if field.excluded("input") {
						continue
					}
				case "TransformOutput":
					if field.excluded("output") {
						continue
					}
				default:
					continue
				}
				name, _ := transformerSpec(annotation.Argument)
				if structTypes[name] {
					fmt.Fprintf(&out, "var _ __nestgo_transform.Transformer[%s] = (*%s)(nil)\n", field.Type, name)
				} else {
					fmt.Fprintf(&out, "var _ __nestgo_transform.Func[%s] = %s\n", field.Type, name)
				}
			}
		}
	}
	out.WriteString(generatedRegexDeclarations(file))
	out.WriteString(propertyMethods(file, structTypes))
	out.WriteString(generatedDTOValidation(file))
	return format.Source([]byte(out.String()))
}

// decoratorOnlyImportAliases identifies qualifiers used in field transformations.
// As generated methods live in a distinct file, their imports cannot remain in
// the original Go source unless other ordinary source expressions use them.
func decoratorOnlyImportAliases(file *File) map[string]bool {
	out := map[string]bool{}
	for _, dto := range file.DTOs {
		for _, field := range dto.Fields {
			for _, ann := range field.Annotations {
				if ann.Name == "Transform" || ann.Name == "TransformInput" || ann.Name == "TransformOutput" || ann.Name == "Validate" {
					fn, err := transformerSpec(ann.Argument)
					if err == nil {
						if alias := transformerQualifier(fn); alias != "" {
							out[alias] = true
						}
					}
				}
			}
		}
	}
	return out
}
