package compiler

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/kevenmiano/nestgo/database/sqlgen"
)

// RepositoryDefinition is the compiler's validated input for emitting repository
// implementations. The .mgo decorator parser will construct this representation.
type RepositoryDefinition struct {
	Package string
	Name    string
	Entity  string
	Fields  []RepositoryField
	Methods []RepositoryMethod
	Dialect sqlgen.Dialect
}

type RepositoryField struct {
	Name string
}

type RepositoryParameter struct {
	Name string
	Type string
}

type RepositoryMethod struct {
	Name       string
	SQL        string
	Parameters []RepositoryParameter
	Many       bool
}

// GenerateRepository emits direct, typed database/sql calls. SQL is compiled once
// at build time, and user-controlled values are always driver arguments.
func GenerateRepository(def RepositoryDefinition) ([]byte, error) {
	if !schemaIdentifier(def.Package) || !schemaIdentifier(def.Name) || !schemaIdentifier(def.Entity) || len(def.Fields) == 0 || len(def.Methods) == 0 {
		return nil, fmt.Errorf("repository: invalid declaration")
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by NestGo. DO NOT EDIT.\npackage %s\n\n", def.Package)
	out.WriteString("import (\n\"context\"\n\"github.com/kevenmiano/nestgo/database\"\n)\n")
	fmt.Fprintf(&out, "type %sGenerated struct { db database.Executor }\n", def.Name)
	fmt.Fprintf(&out, "func New%sGenerated(db database.Executor) *%sGenerated { return &%sGenerated{db:db} }\n", def.Name, def.Name, def.Name)
	seen := make(map[string]bool)
	for _, method := range def.Methods {
		if !schemaIdentifier(method.Name) || seen[method.Name] {
			return nil, fmt.Errorf("repository: invalid or duplicate method %q", method.Name)
		}
		seen[method.Name] = true
		if !strings.HasPrefix(strings.ToUpper(strings.TrimSpace(method.SQL)), "SELECT ") {
			return nil, fmt.Errorf("repository: %s must be a SELECT query", method.Name)
		}
		names := make([]string, len(method.Parameters))
		bound := make(map[string]any, len(method.Parameters))
		for i, param := range method.Parameters {
			if !schemaIdentifier(param.Name) || !repositorySafeType(param.Type) {
				return nil, fmt.Errorf("repository: unsafe parameter declaration in %s", method.Name)
			}
			if _, exists := bound[param.Name]; exists {
				return nil, fmt.Errorf("repository: duplicate parameter %q", param.Name)
			}
			names[i] = param.Name
			bound[param.Name] = i
		}
		query, order, err := sqlgen.Bind(method.SQL, bound, def.Dialect)
		if err != nil {
			return nil, err
		}
		var args []string
		for _, index := range order {
			args = append(args, names[index.(int)])
		}
		signature := "(*" + def.Entity + ", error)"
		if method.Many {
			signature = "([]" + def.Entity + ", error)"
		}
		fmt.Fprintf(&out, "func (r *%sGenerated) %s(ctx context.Context", def.Name, method.Name)
		for _, param := range method.Parameters {
			fmt.Fprintf(&out, ", %s %s", param.Name, param.Type)
		}
		fmt.Fprintf(&out, ") %s {\n", signature)
		fmt.Fprintf(&out, "const query = %s\n", strconv.Quote(query))
		callArgs := ""
		for _, name := range args {
			callArgs += ", " + name
		}
		fields := make([]string, 0, len(def.Fields))
		for _, field := range def.Fields {
			if !schemaIdentifier(field.Name) {
				return nil, fmt.Errorf("repository: invalid scan field %q", field.Name)
			}
			fields = append(fields, "&row."+field.Name)
		}
		if method.Many {
			fmt.Fprintf(&out, "rows, err := r.db.QueryContext(ctx, query%s)\nif err != nil {return nil,err}\ndefer rows.Close()\n", callArgs)
			fmt.Fprintf(&out, "result := make([]%s, 0)\nfor rows.Next() {var row %s\nif err := rows.Scan(%s);err != nil{return nil,err}\nresult=append(result,row)}\nif err:=rows.Err();err!=nil{return nil,err}\nreturn result,nil\n", def.Entity, def.Entity, strings.Join(fields, ","))
		} else {
			fmt.Fprintf(&out, "var row %s\nerr := r.db.QueryRowContext(ctx, query%s).Scan(%s)\n", def.Entity, callArgs, strings.Join(fields, ","))
			out.WriteString("if err != nil {return nil,err}\nreturn &row,nil\n")
		}
		out.WriteString("}\n")
	}
	return format.Source([]byte(out.String()))
}

func repositorySafeType(typ string) bool {
	switch typ {
	case "string", "int", "int64", "int32", "bool", "float64", "float32", "[]byte":
		return true
	default:
		return false
	}
}
