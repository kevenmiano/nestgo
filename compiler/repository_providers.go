package compiler

import (
	"fmt"
	"go/format"
	"strings"
)

// GenerateRepositoryProviders emits a bootstrap constructor registry for
// named repositories. The caller supplies initialized database connections;
// all lookups occur once during bootstrap, not during query execution.
func GenerateRepositoryProviders(packageName string, definitions []RepositoryDefinition) ([]byte, error) {
	if !schemaIdentifier(packageName) {
		return nil, fmt.Errorf("repository providers: invalid package")
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by NestGo. DO NOT EDIT.\npackage %s\n\n", packageName)
	out.WriteString("import (\n\"fmt\"\n\"github.com/kevenmiano/nestgo/database\"\n)\n")
	out.WriteString("type GeneratedRepositories struct {\n")
	for _, def := range definitions {
		if !schemaIdentifier(def.Name) || def.Connection == "" {
			return nil, fmt.Errorf("repository providers: %s requires a named connection", def.Name)
		}
		fmt.Fprintf(&out, "%s *%sGenerated\n", def.Name, def.Name)
	}
	out.WriteString("}\n")
	out.WriteString("func NewGeneratedRepositories(connections *database.Connections) (*GeneratedRepositories, error) {\n")
	out.WriteString("if connections == nil { return nil, fmt.Errorf(\"repository providers: nil connections\") }\nresult := &GeneratedRepositories{}\n")
	for _, def := range definitions {
		fmt.Fprintf(&out, "var err%s error\nresult.%s, err%s = New%sGeneratedFromConnections(connections)\nif err%s != nil { return nil, err%s }\n", def.Name, def.Name, def.Name, def.Name, def.Name, def.Name)
	}
	out.WriteString("return result, nil\n}\n")
	out.WriteString("func (r *GeneratedRepositories) Instances() []any {\nif r == nil { return nil }\nreturn []any{\n")
	for _, def := range definitions {
		fmt.Fprintf(&out, "r.%s,\n", def.Name)
	}
	out.WriteString("}\n}\n")
	return format.Source([]byte(out.String()))
}
