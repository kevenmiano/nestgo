// wiringTestSource generates assertions against the exact registry emitted by
// Generate. The output is owned by the compiler and may be regenerated.
func wiringTestSource(files []*File) ([]byte, error) {
	if len(files) == 0 {
		return nil, fmt.Errorf("no source files")
	}
	type route struct {
		method, path, handler string
		status                int
	}
	type controller struct {
		name, prefix string
		routes       []route
	}
	type module struct{ name, label string }
	controllers := map[string]*controller{}
	providers := []string{}
	modules := []module{}
	for _, file := range files {
		for _, decl := range file.Declarations {
			if decl.Kind != "type" {
				continue
			}
			for _, annotation := range decl.Annotations {
				switch annotation.Name {
				case "Controller":
					prefix, err := arg(annotation, "/")
					if err != nil {
						return nil, err
					}
					controllers[decl.Name] = &controller{name: decl.Name, prefix: prefix}
				case "Injectable":
					providers = append(providers, decl.Name)
				case "Module":
					options, err := parseModuleOptions(file.Path, annotation, decl.Name)
					if err != nil {
						return nil, err
					}
					modules = append(modules, module{decl.Name, options.Name})
				}
			}
		}
	}
	for _, file := range files {
		for _, decl := range file.Declarations {
			if decl.Kind != "func" {
				continue
			}
			c := controllers[decl.Receiver]
			if c == nil {
				continue
			}
			status := 0
			for _, annotation := range decl.Annotations {
				if annotation.Name == "HttpCode" {
					status, _ = strconv.Atoi(annotation.Argument) // validated by Generate
				}
			}
			for _, annotation := range decl.Annotations {
				if !isRoute(annotation.Name) {
					continue
				}
				path, err := arg(annotation, "/")
				if err != nil {
					return nil, err
				}
				c.routes = append(c.routes, route{strings.ToUpper(annotation.Name), path, decl.Name, status})
			}
		}
	}
	sort.Strings(providers)
	sort.Slice(modules, func(i, j int) bool { return modules[i].name < modules[j].name })
	names := make([]string, 0, len(controllers))
	for name := range controllers {
		names = append(names, name)
	}
	sort.Strings(names)

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by NestGo compiler. DO NOT EDIT.\npackage %s\n\n", files[0].Package)
	out.WriteString("import (\n\"reflect\"\n\"testing\"\nnestgometa \"github.com/kevenmiano/nestgo/metadata\"\n)\n\n")
	out.WriteString("type nestgoExpectedRoute struct { method, path, handler string; status int }\n")
	out.WriteString("type nestgoExpectedController struct { typ reflect.Type; prefix string; routes []nestgoExpectedRoute }\n\n")
	out.WriteString("func TestNestGoCompiledWiring(t *testing.T) {\n")
	fmt.Fprintf(&out, "pkg, ok := nestgometa.Lookup(%q)\nif !ok { t.Fatal(\"compiled metadata not registered\") }\n", files[0].Package)
	fmt.Fprintf(&out, "if got := len(pkg.Providers); got != %d { t.Fatalf(\"provider count = %%d, want %d\", got) }\n", len(providers), len(providers))
	for _, name := range providers {
		fmt.Fprintf(&out, "func() { want := reflect.TypeOf((*%s)(nil)); for _, got := range pkg.Providers { if got.Type == want { return } }; t.Errorf(\"provider %%s missing from compiled wiring\", want) }()\n", name)
	}
	fmt.Fprintf(&out, "if got := len(pkg.Modules); got != %d { t.Fatalf(\"module count = %%d, want %d\", got) }\n", len(modules), len(modules))
	for _, item := range modules {
		fmt.Fprintf(&out, "func() { want := reflect.TypeOf((*%s)(nil)); for _, got := range pkg.Modules { if got.Type == want && got.Name == %q { return } }; t.Errorf(\"module %%s missing or incorrectly named\", want) }()\n", item.name, item.label)
	}
	fmt.Fprintf(&out, "if got := len(pkg.Controllers); got != %d { t.Fatalf(\"controller count = %%d, want %d\", got) }\n", len(names), len(names))
	out.WriteString("for _, want := range []nestgoExpectedController{\n")
	for _, name := range names {
		c := controllers[name]
		sort.Slice(c.routes, func(i, j int) bool {
			a, b := c.routes[i], c.routes[j]
			return a.method+a.path+a.handler < b.method+b.path+b.handler
		})
		fmt.Fprintf(&out, "{typ: reflect.TypeOf((*%s)(nil)), prefix: %q, routes: []nestgoExpectedRoute{\n", name, c.prefix)
		for _, route := range c.routes {
			fmt.Fprintf(&out, "{method:%q,path:%q,handler:%q,status:%d},\n", route.method, route.path, route.handler, route.status)
		}
		out.WriteString("}},\n")
	}
	out.WriteString("} {\n")
	out.WriteString("var actual *nestgometa.Controller\nfor i := range pkg.Controllers { if pkg.Controllers[i].Type == want.typ { actual = &pkg.Controllers[i]; break } }\n")
	out.WriteString("if actual == nil { t.Errorf(\"controller %s missing\", want.typ); continue }\n")
	out.WriteString("if actual.Prefix != want.prefix { t.Errorf(\"%s prefix = %q, want %q\", want.typ, actual.Prefix, want.prefix) }\n")
	out.WriteString("if len(actual.Routes) != len(want.routes) { t.Errorf(\"%s has %d routes, want %d\", want.typ, len(actual.Routes), len(want.routes)); continue }\n")
	out.WriteString("for _, route := range want.routes { found := false; for _, got := range actual.Routes { if got.Method == route.method && got.Path == route.path && got.Handler == route.handler && got.Status == route.status { found = true; break } }; if !found { t.Errorf(\"%s missing compiled route %s %s (%s, status %d)\", want.typ, route.method, route.path, route.handler, route.status) } }\n")
	out.WriteString("}\n}\n")
	return format.Source([]byte(out.String()))
}

// testStubName preserves conventional names for exported types and makes
// lowercase decorated types discoverable by the go test runner.
func testStubName(typeName, method string) string {
	prefix := "Test"
	if len(typeName) > 0 && unicode.IsLower([]rune(typeName)[0]) {
		prefix = "TestNestGo_"
	}
	name := prefix + typeName
	if method != "" {
		name += "_" + method
	}
	return name
}

type editableTestStub struct {
	name       string
	typeName   string
	dependency []string
}

// editableStubs makes one unit-test TODO for each decorated type and route.
// Stubs are deliberately NOT regenerated: the developer owns their assertions.
func editableStubs(files []*File) ([]editableTestStub, error) {
	byName := map[string]editableTestStub{}
	for _, file := range files {
		fset := token.NewFileSet()
		node, err := parser.ParseFile(fset, file.Path, file.Source, 0)
		if err != nil {
			return nil, err
		}
		fields := map[string][]string{}
		for _, decl := range node.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				typ, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := typ.Type.(*ast.StructType)
				if !ok {
					continue
				}
				for _, field := range st.Fields.List {
					if len(field.Names) == 0 {
						continue
					}
					if field.Tag != nil {
						tag, err := strconv.Unquote(field.Tag.Value)
						if err == nil && reflect.StructTag(tag).Get("nestgo") == "-" {
							continue
						}
					}
					var printed bytes.Buffer
					if err := format.Node(&printed, fset, field.Type); err != nil {
						return nil, err
					}
					for _, name := range field.Names {
						fields[typ.Name.Name] = append(fields[typ.Name.Name], name.Name+" "+printed.String())
					}
				}
			}
		}
		for _, declaration := range file.Declarations {
			if declaration.Kind == "type" {
				for _, annotation := range declaration.Annotations {
					if annotation.Name == "Controller" || annotation.Name == "Injectable" {
						name := testStubName(declaration.Name, "")
						byName[name] = editableTestStub{name: name, typeName: declaration.Name, dependency: fields[declaration.Name]}
					}
				}
			}
			if declaration.Kind == "func" {
				for _, annotation := range declaration.Annotations {
					if isRoute(annotation.Name) {
						name := testStubName(declaration.Receiver, declaration.Name)
						byName[name] = editableTestStub{name: name, typeName: declaration.Receiver, dependency: fields[declaration.Receiver]}
					}
				}
			}
		}
	}
	names := make([]string, 0, len(byName))
	for name := range byName {
		names = append(names, name)
	}
	sort.Strings(names)
	result := make([]editableTestStub, 0, len(names))
	for _, name := range names {
		result = append(result, byName[name])
	}
	return result, nil
}

// appendMissingTestStubs only appends missing names; it never rewrites user code.
// User-defined tests anywhere in the package win over generated TODOs.
func appendMissingTestStubs(dir, pkg string, stubs []editableTestStub) error {
	if len(stubs) == 0 {
		return nil
	}
	paths, err := filepath.Glob(filepath.Join(dir, "*_test.go"))
	if err != nil {
		return err
	}
	existing := map[string]bool{}
	target := filepath.Join(dir, "zz_nestgo_stubs_test.go")
	for _, path := range paths {
		node, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.AllErrors)
		if err != nil {
			return fmt.Errorf("read existing tests %s: %w", path, err)
		}
		if path == target && node.Name.Name != pkg {
			return fmt.Errorf("test stub package %s differs from %s", node.Name.Name, pkg)
		}
		for _, declaration := range node.Decls {
			fn, ok := declaration.(*ast.FuncDecl)
			if ok && fn.Recv == nil {
				existing[fn.Name.Name] = true
			}
		}
	}
	var source strings.Builder
	for _, stub := range stubs {
		if existing[stub.name] {
			continue
		}
		fmt.Fprintf(&source, "\nfunc %s(t *testing.T) {\n", stub.name)
		for _, dependency := range stub.dependency {
			fmt.Fprintf(&source, "// Wiring field: %s\n", dependency)
		}
		fmt.Fprintf(&source, "subject := new(%s)\n_ = subject\n", stub.typeName)
		fmt.Fprintf(&source, "t.Skip(%q)\n}\n", "TODO: add assertions for "+stub.name)
	}
	if source.Len() == 0 {
		return nil
	}
	if _, err := os.Lstat(target); os.IsNotExist(err) {
		header := fmt.Sprintf("// Editable test stubs created by NestGo. Add assertions; recompilation preserves them.\npackage %s\n\nimport \"testing\"\n", pkg)
		sourceText := header + source.String()
		formatted, err := format.Source([]byte(sourceText))
		if err != nil {
			return err
		}
		file, err := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
		if err == nil {
			defer file.Close()
			_, err = file.Write(formatted)
			return err
		}
		if !os.IsExist(err) {
			return err
		}
	} else if err != nil {
		return err
	}
	info, err := os.Lstat(target)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("test stub path %s is not a regular file", target)
	}
	// Appending rather than formatting the entire file preserves custom edits.
	file, err := os.OpenFile(target, os.O_WRONLY|os.O_APPEND, 0)
	if err != nil {
		return err
	}
	defer file.Close()
	formatted, err := format.Source([]byte("package " + pkg + "\nimport \"testing\"\n" + source.String()))
	if err != nil {
		return err
	}
	// Only append declarations; the existing file already has package/imports.
	_, err = file.Write(formatted[bytes.Index(formatted, []byte("\nfunc ")):])
	return err
}
