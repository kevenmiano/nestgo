package compiler

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path"
	"strconv"
	"strings"
)

// generatedSource removes imports referenced only by @Module metadata.
// The source .mgo is preserved; the metadata file imports these aliases instead.
func generatedSource(file *File) ([]byte, error) {
	decoratorAliases := make(map[string]bool)
	for _, declaration := range file.Declarations {
		for _, annotation := range declaration.Annotations {
			if annotation.Name != "Module" {
				continue
			}
			options, err := parseModuleOptions(file.Path, annotation, declaration.Name)
			if err != nil {
				return nil, err
			}
			for _, imported := range options.Imports {
				if prefix, _, ok := strings.Cut(imported, "."); ok {
					decoratorAliases[prefix] = true
				}
			}
		}
	}
	if len(decoratorAliases) == 0 {
		return format.Source([]byte("// Code generated by NestGo compiler. DO NOT EDIT.\n" + file.Source))
	}
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, file.Path, file.Source, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	used := make(map[string]bool)
	ast.Inspect(node, func(n ast.Node) bool {
		if selector, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := selector.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	declarations := node.Decls[:0]
	for _, declaration := range node.Decls {
		g, ok := declaration.(*ast.GenDecl)
		if !ok || g.Tok != token.IMPORT {
			declarations = append(declarations, declaration)
			continue
		}
		specs := g.Specs[:0]
		for _, spec := range g.Specs {
			imp := spec.(*ast.ImportSpec)
			importPath, err := strconv.Unquote(imp.Path.Value)
			if err != nil {
				return nil, err
			}
			alias := path.Base(importPath)
			if imp.Name != nil {
				alias = imp.Name.Name
			}
			if decoratorAliases[alias] && !used[alias] {
				continue
			}
			specs = append(specs, spec)
		}
		g.Specs = specs
		if len(specs) > 0 {
			declarations = append(declarations, g)
		}
	}
	node.Decls = declarations
	var out bytes.Buffer
	out.WriteString("// Code generated by NestGo compiler. DO NOT EDIT.\n")
	if err := format.Node(&out, fset, node); err != nil {
		return nil, err
	}
	return format.Source(out.Bytes())
}
